stopifnot(length(node_x) == d, length(node_y) == d)
label_y <- node_y - 3.20

write_graph_tikz <- function(adj, file_out) {
  con <- file(file_out, open = "w")
  on.exit(close(con), add = TRUE)
  cat(file = con,
      "% Auto-generated by generate_danube_tikz.R\n",
      "\\begin{tikzpicture}[x=1pt,y=1pt]\n",
      "\\definecolor{fillColor}{RGB}{255,255,255}\n",
      "\\path[use as bounding box,fill=fillColor,fill opacity=0.00] (0,0) rectangle (433.62,433.62);\n",
      "\\begin{scope}\n",
      "\\path[clip] ( 49.20, 61.20) rectangle (408.42,384.42);\n",
      "\\definecolor{drawColor}{RGB}{169,169,169}\n\n",
      sep = "")
  for (i in seq_len(d - 1)) {
    for (j in seq.int(i + 1, d)) {
      if (!isTRUE(adj[i, j])) next
      cat(file = con, sprintf(
        "\\path[draw=drawColor,line width= 0.8pt,line join=round,line cap=round] (%6.2f,%6.2f) -- (%6.2f,%6.2f);\n\n",
        node_x[i], node_y[i], node_x[j], node_y[j]))
    }
  }
  cat(file = con,
      "\\definecolor{drawColor}{RGB}{0,0,0}\n",
      "\\definecolor{fillColor}{RGB}{173,216,230}\n\n",
      sep = "")
  for (i in seq_len(d)) {
    cat(file = con, sprintf(
      "\\path[draw=drawColor,line width= 0.4pt,line join=round,line cap=round,fill=fillColor] (%6.2f,%6.2f) circle (  7.13);\n\n",
      node_x[i], node_y[i]))
  }
  cat(file = con, "\\end{scope}\n\\begin{scope}\n",
      "\\path[clip] (  0.00,  0.00) rectangle (433.62,433.62);\n",
      "\\definecolor{drawColor}{RGB}{0,0,139}\n\n",
      sep = "")
  for (i in seq_len(d)) {
    cat(file = con, sprintf(
      "\\node[text=drawColor,anchor=base,inner sep=0pt, outer sep=0pt, scale=  1.00] at (%6.2f,%6.2f) {%d};\n\n",
      node_x[i], label_y[i], i))
  }
  cat(file = con, "\\end{scope}\n\\end{tikzpicture}\n", sep = "")
}

out_emtp2 <- normalizePath("../emtp2_graph.tex", winslash = "/", mustWork = FALSE)
out_sp    <- normalizePath("../spectral_hr_bic_graph.tex", winslash = "/", mustWork = FALSE)
write_graph_tikz(emtp2_adj, out_emtp2)
write_graph_tikz(sp_adj,    out_sp)
cat(sprintf("Wrote %s\n", out_emtp2))
cat(sprintf("Wrote %s\n", out_sp))
