# TikZ drawings of the estimated Danube graphs.

suppressPackageStartupMessages({
  library(MASS); library(igraph); library(graphicalExtremes)
})
source("experiment_helpers.R")

data(danube, package = "graphicalExtremes")
X <- danube$data_clustered
d <- ncol(X)
p_thresh <- 0.90
Gamma_full <- emp_vario(data = X, p = p_thresh)

K_emtp2 <- fit_emtp2(Gamma_full)
emtp2_adj <- (abs(K_emtp2) > 1e-3) & (row(K_emtp2) != col(K_emtp2))

eta_bic <- 4
mle <- hr_mle_dense(Gamma_full, tol = 1e-8, maxiter = 3000)
sp_res <- spectral_hr_from_mle(mle, eta_bic, tol = 1e-8, maxiter = 3000)
K_spectral <- sp_res$Theta_refit
sp_adj <- (abs(K_spectral) > 1e-3) & (row(K_spectral) != col(K_spectral))

cat(sprintf("EMTP2 edges: %d\n", sum(emtp2_adj[upper.tri(emtp2_adj)])))
cat(sprintf("Spectral-HR (BIC-selected eta=%g) edges: %d\n",
            eta_bic, sum(sp_adj[upper.tri(sp_adj)])))

node_x <- c(257.31, 200.31, 143.30, 143.30, 200.31, 200.31, 200.31,
